/**
 * Full-run EXECUTION MACHINERY, end to end, on a computation nobody hand-wrote.
 *
 * `tests/full-run.test.ts` proves the plumbing (authorization, work list,
 * faults, idempotency) on a fixture whose baseline number is a constant the
 * suite wrote into `experiment result`, and whose idea prints `0.5`. That is the
 * right fixture for testing the plumbing, and it is the wrong fixture for
 * asking whether the plumbing can carry science: nothing in it could ever have
 * been WRONG, so nothing in it is checked by a number.
 *
 * This file drives the documented chain (docs/FULL_RESEARCH_MODE.md,
 * docs/DATA_SCALE_POLICY.md) — idea create → implement → check → experiment →
 * analyze → handoff → full fairness → full plan → full approve → full run — in
 * a temporary project where:
 *
 *   - the dataset is a real CSV (a synthetic-but-genuine 340:60 class
 *     imbalance, generated by hash, byte-identical in every tree, hash-checked);
 *   - the required comparison is a paper-reimplementation executed by
 *     `baseline reproduce`, which fits its decision rule and scores a held-out
 *     split. Its metric is a number a Python process computed;
 *   - the idea is a different objective on the same table (class-frequency
 *     weighting instead of per-sample weighting) and it wins the protocol's
 *     primary metric because the pooled-error optimum collapses onto the
 *     majority class. `idea analyze` returns SUPPORTED on that arithmetic.
 *
 * No metric in this file is written by the test. Every value asserted was
 * produced by a child process reading the CSV, which is what the platform's
 * anti-synthetic guards (src/idea/check.ts smoke gate,
 * src/comparison/reproduce.ts scale/skip honesty, RunResult recording) insist
 * on anyway.
 *
 * What is under test is the machinery, not the science:
 *   1. the approved work list really executes — every required method plus the
 *      idea version — and lands in the unified registry plus the full-run report;
 *   2. the capacity gate refuses a declared demand the machine cannot meet,
 *      with the recovery message, instead of running anyway;
 *   3. a hard pause interrupts the task between work items, and the completed
 *      item is not re-executed when the list is run again;
 *   4. a stale authorization never executes.
 */

