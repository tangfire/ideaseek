function metricOf(doc: RegistryDoc, name: string): number {
  const found = (doc.result?.metrics ?? []).find((metric) => metric.name === name);
  if (!found) throw new Error(`${doc.specId} has no metric ${name}`);
  return found.value;
}

function scaleOf(doc: RegistryDoc): string {
  const note = (doc.spec.environment.notes ?? []).find((entry) => entry.startsWith('scale:'));
  return note ? note.slice('scale:'.length) : 'unknown';
}

