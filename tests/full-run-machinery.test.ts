/**
 * Deterministic 32-bit mixer — not a cipher, just a stable map from an index to
 * [0,1). A congruential stream was tried first and its low bits correlated the
 * x-draws with the split-draws, which silently produced a 24/400 train split.
 */
function unit(seed: number): number {
  let x = (Math.imul(seed, 2654435761) ^ 0x5bf03635) >>> 0;
  x = Math.imul(x ^ (x >>> 15), 2246822507) >>> 0;
  x = Math.imul(x ^ (x >>> 13), 3266489909) >>> 0;
  return ((x ^ (x >>> 16)) >>> 0) / 4294967296;
}

/**
 * The synthetic dataset: 340 majority rows spread over [0,2] and 60 minority
 * rows over [1.4,2.4], sorted by feature value, with a 60/40 train/test split
 * drawn from an independent stream. The classes overlap in [1.4,2], so
 * per-sample error is minimised by predicting the majority class almost
 * everywhere (minority recall collapses), while per-class error is minimised by
 * a threshold near 1.4. Both rules are run, neither number is declared.
 */
function datasetCsv(): string {
  interface Row {
    x: number;
    label: number;
    split: string;
  }
  const rows: Row[] = [];
  for (let i = 0; i < 340; i += 1) {
    rows.push({ x: unit(i) * 2, label: 0, split: unit(9000 + i) < 0.6 ? 'train' : 'test' });
  }
  for (let i = 0; i < 60; i += 1) {
    rows.push({
      x: 1.4 + unit(50000 + i),
      label: 1,
      split: unit(60000 + i) < 0.6 ? 'train' : 'test',
    });
  }
  rows.sort((a, b) => a.x - b.x);
  const lines = ['x,label,split'];
  for (const row of rows) lines.push(`${row.x.toFixed(4)},${row.label},${row.split}`);
  return `${lines.join('\n')}\n`;
}

function sha256Text(text: string): string {
  return createHash('sha256').update(text, 'utf8').digest('hex');
}

