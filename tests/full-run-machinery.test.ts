interface RegistryDoc {
  specId: string;
  version: number;
  status: string;
  spec: {
    idea: { ideaId: string; version: number } | null;
    comparisonIds: string[];
    command: string[];
    metrics: { name: string; direction: string }[];
    seeds: number[];
    dataSnapshotId: string;
    protocolId: string | null;
    resources: Record<string, unknown>;
    environment: { notes: string[] };
  };
  result: {
    status: string;
    metrics: { name: string; value: number }[];
    explanation?: string;
    failure?: { category: string; summary: string } | null;
  } | null;
}

async function showExperiment(dir: string, specId: string): Promise<RegistryDoc> {
  const shown = await runCli(dir, ['experiment', 'show', specId, '--json']);
  expect(shown.code, shown.stdout + shown.stderr).toBe(0);
  return JSON.parse(shown.stdout) as RegistryDoc;
}

function metricOf(doc: RegistryDoc, name: string): number {
  const found = (doc.result?.metrics ?? []).find((metric) => metric.name === name);
  if (!found) throw new Error(`${doc.specId} has no metric ${name}`);
  return found.value;
}

function scaleOf(doc: RegistryDoc): string {
  const note = (doc.spec.environment.notes ?? []).find((entry) => entry.startsWith('scale:'));
  return note ? note.slice('scale:'.length) : 'unknown';
}

interface FullRunReport {
  contract: string;
  ideaId: string;
  planInputHash: string;
  items: {
    kind: string;
    id: string;
    status: string;
    metrics: { name: string; value: number }[];
  }[];
}

async function fullRunReports(dir: string): Promise<FullRunReport[]> {
  const rt = await openRuntime(dir, { recover: false });
  try {
    const rows = await rt.db.listArtifactsByKind('full-run-report');
    const out: FullRunReport[] = [];
    for (const row of rows) {
      out.push(JSON.parse(await rt.store.readFinalText(row.contentHash)) as FullRunReport);
    }
    return out;
  } finally {
    await rt.close();
  }
}

async function taskState(
  dir: string,
  runId: string,
  type: string,
): Promise<{ status: string; attemptsMade: number; error: { code: string; message: string } | null }> {
  const rt = await openRuntime(dir, { recover: false });
  try {
    const tasks = await rt.db.listTasks(runId);
    const task = tasks.filter((row) => row.type === type).pop();
    if (!task) throw new Error(`no ${type} task in ${runId}`);
    return {
      status: task.status,
      attemptsMade: task.attempt,
      error: task.error ? { code: task.error.code, message: task.error.message } : null,
    };
  } finally {
    await rt.close();
  }
}

