/**
 * The documented route, all of it through the CLI, to an APPROVED full plan over
 * a genuinely winning idea. Returns the numbers the chain computed so each test
 * can assert the full run reproduces them rather than inventing new ones.
 */
async function setupApprovedProject(dir: string): Promise<SetupFacts> {
  const csv = datasetCsv();
  const datasetHash = sha256Text(csv);

  // 1. the dataset lands in the read-only inputs dir, then is bound to both
  //    trees by content hash (never by a declared number).
  await mkdir(join(dir, 'datasets', 'imbalance'), { recursive: true });
  await writeFile(join(dir, 'datasets', 'imbalance', 'samples.csv'), csv, 'utf8');

  // 2. idea workspace (card + scaffold) bound to that input file.
  const cardPath = join(dir, 'card.json');
  await writeFile(cardPath, JSON.stringify(makeCard(), null, 2), 'utf8');
  const created = await runCli(dir, [
    'idea',
    'create',
    IDEA,
    '--from-card',
    cardPath,
    '--data',
    join('datasets', 'imbalance', 'samples.csv'),
  ]);
  expect(created.code, created.stdout + created.stderr).toBe(0);

  // 3. the required comparison, registered as a paper reimplementation with its
  //    own copy of the same bytes.
  const register = await runCli(dir, [
    'comparison',
    'register',
    BASELINE,
    '--source',
    'paper-reimplementation',
    '--paper',
    'he13a-imbalanced',
    '--json',
  ]);
  expect(register.code, register.stdout + register.stderr).toBe(0);
  await mkdir(join(dir, 'comparisons', BASELINE, 'worktree', 'data'), { recursive: true });
  await writeFile(join(dir, 'comparisons', BASELINE, 'worktree', 'data', 'samples.csv'), csv, 'utf8');
  await mkdir(join(dir, 'comparisons', BASELINE), { recursive: true });
  await writeFile(
    join(dir, 'comparisons', BASELINE, 'blueprint.json'),
    JSON.stringify(blueprint(BASELINE), null, 2),
    'utf8',
  );

  // 4. lock the protocol before anything measures anything: its metric names are
  //    the contract the entries are held to.
  await seedAndConfirmProtocol(dir);

  // 5. the baseline is EXECUTED, not declared: check-code/check-data/
  //    check-metrics/smoke all run in the worktree.
  const repro = await runCli(dir, [
    'baseline',
    'reproduce',
    '--method',
    BASELINE,
    '--data',
    join('data', 'samples.csv'),
    '--json',
  ]);
  expect(repro.code, repro.stdout + repro.stderr).toBe(0);
  const reproPayload = JSON.parse(repro.stdout) as {
    outcome: string;
    specId: string;
    smokeMetrics: { name: string; value: number }[];
  };
  expect(reproPayload.outcome).toBe('validated');
  expect(reproPayload.specId).toBe(`repro-${BASELINE}`);
  const reproDoc = await showExperiment(dir, `repro-${BASELINE}`);
  expect(reproDoc.status).toBe('succeeded');
  expect(reproDoc.spec.idea).toBeNull();
  expect(reproDoc.spec.comparisonIds).toEqual([BASELINE]);
  expect(scaleOf(reproDoc)).toBe('smoke');
  const baselineSmokeValue = metricOf(reproDoc, PRIMARY);

  // 6. implement the idea by hand (the non-model route): real code in the
  //    workspace, reading the same bytes.
  expect((await runCli(dir, ['idea', 'set-status', IDEA, 'IMPLEMENTING'])).code).toBe(0);
  const ideaData = join(dir, 'ideas', IDEA, 'data');
  await mkdir(ideaData, { recursive: true });
  await writeFile(join(ideaData, 'samples.csv'), csv, 'utf8');
  // "The same dataset" is a checked fact here, not a claim: the inputs copy,
  // the comparison worktree copy and the idea workspace copy are one byte
  // sequence, and the idea's data manifest hashes the declared input.
  expect(sha256Text(await readFile(join(ideaData, 'samples.csv'), 'utf8'))).toBe(datasetHash);
  expect(
    sha256Text(
      await readFile(join(dir, 'comparisons', BASELINE, 'worktree', 'data', 'samples.csv'), 'utf8'),
    ),
  ).toBe(datasetHash);
  const src = join(dir, 'ideas', IDEA, 'src');
  await mkdir(join(src, 'tests'), { recursive: true });
  await writeFile(join(src, 'smoke.py'), IDEA_SMOKE_PROGRAM, 'utf8');
  await writeFile(join(src, 'train.py'), IDEA_TRAIN_PROGRAM, 'utf8');
  await writeFile(
    join(src, 'check_data.py'),
    '"""Data interface check: the bound CSV holds both classes and both splits."""\n' +
      'import csv\nimport os\nimport sys\n\n' +
      'path = os.path.join("data", "samples.csv")\n' +
      'with open(path, newline="") as fh:\n' +
      '    rows = list(csv.DictReader(fh))\n' +
      'if len(rows) < 50 or len({r["label"] for r in rows}) != 2 or len({r["split"] for r in rows}) != 2:\n' +
      '    sys.stderr.write("data interface does not hold\\n")\n' +
      '    raise SystemExit(1)\n' +
      'raise SystemExit(0)\n',
    'utf8',
  );
  await writeFile(
    join(src, 'check_metrics.py'),
    '"""Metric computability check: both protocol metrics are float-valued."""\n' +
      'import json\nimport subprocess\nimport sys\n\n' +
      'run = subprocess.run([sys.executable, "src/smoke.py"], capture_output=True, text=True)\n' +
      'line = [l for l in run.stdout.splitlines() if l.strip().startswith("{")][-1]\n' +
      'metrics = json.loads(line)["metrics"]\n' +
      'missing = [n for n in ("balanced_accuracy", "minority_recall") if not isinstance(metrics.get(n), float)]\n' +
      'if missing:\n' +
      '    sys.stderr.write("not computable: %s\\n" % ", ".join(missing))\n' +
      '    raise SystemExit(1)\n' +
      'raise SystemExit(0)\n',
    'utf8',
  );
  await writeFile(
    join(src, 'tests', 'test_weighting.py'),
    '"""The two objectives must disagree on this table, or the idea is a no-op."""\n' +
      'import unittest\n\n' +
      'from src import smoke\n\n\n' +
      'class WeightingTest(unittest.TestCase):\n' +
      '    def test_balanced_objective_prefers_the_minority_cut(self):\n' +
      '        rows = smoke.load(smoke.DATA)\n' +
      '        train = [r for r in rows if r[2] == "train"]\n' +
      '        cut_low = smoke.scores(train, 1.41)\n' +
      '        cut_high = smoke.scores(train, 2.01)\n' +
      '        self.assertGreater(smoke.objective(cut_low), smoke.objective(cut_high))\n\n' +
      '    def test_accuracy_objective_prefers_the_majority_cut(self):\n' +
      '        rows = smoke.load(smoke.DATA)\n' +
      '        train = [r for r in rows if r[2] == "train"]\n' +
      '        cut_low = smoke.scores(train, 1.41)\n' +
      '        cut_high = smoke.scores(train, 2.01)\n' +
      '        self.assertGreater(cut_high["accuracy"], cut_low["accuracy"])\n\n\n' +
      'if __name__ == "__main__":\n' +
      '    unittest.main()\n',
    'utf8',
  );
  await writeIdeaConfig(dir, { gpus: 0, memoryGiB: 0.5 });

  const check = await runCli(dir, ['idea', 'check', IDEA, '--json']);
  expect(check.code, check.stdout + check.stderr).toBe(0);
  expect((JSON.parse(check.stdout) as { outcome: string }).outcome, check.stdout).toBe('passed');

  // 7. two scales (the coverage ladder needs smoke AND quick) walking the idea
  //    back through NEEDS_REVISION → IMPLEMENTING → check between them.
  const smokeRun = await runCli(dir, [
    'idea',
    'experiment',
    IDEA,
    '--scale',
    'smoke',
    '--json',
  ]);
  expect(smokeRun.code, smokeRun.stdout + smokeRun.stderr).toBe(0);
  expect(
    (
      await runCli(dir, [
        'idea',
        'set-status',
        IDEA,
        'NEEDS_REVISION',
        '--reason',
        'second scale',
      ])
    ).code,
  ).toBe(0);
  expect((await runCli(dir, ['idea', 'set-status', IDEA, 'IMPLEMENTING'])).code).toBe(0);
  expect((await runCli(dir, ['idea', 'check', IDEA, '--json'])).code).toBe(0);
  const quickRun = await runCli(dir, ['idea', 'experiment', IDEA, '--scale', 'quick', '--json']);
  expect(quickRun.code, quickRun.stdout + quickRun.stderr).toBe(0);

  const quickDoc = await showExperiment(dir, `idea-${IDEA}`);
  const ideaQuickValue = metricOf(quickDoc, PRIMARY);
  expect(scaleOf(quickDoc)).toBe('quick');
  const ideaSnapshot = quickDoc.spec.dataSnapshotId;
  // The dataset binding is the manifest hash, not a label: `idea create --data`
  // recorded the input file and the spec carries its content hash.
  expect(ideaSnapshot.startsWith('inputs:')).toBe(true);

  // Both idea scales, read from the immutable workspace mirrors (the registry
  // row only keeps the latest version), beat the executed baseline number.
  const mirrors = await Promise.all(
    [1, 2].map(async (version) =>
      JSON.parse(
        await readFile(
          join(dir, 'ideas', IDEA, 'experiments', `idea-${IDEA}-v${version}.json`),
          'utf8',
        ),
      ) as { spec: { environment: { notes: string[] } }; result: { metrics: { name: string; value: number }[] } },
    ),
  );
  const scaleValues = new Map(
    mirrors.map((mirror) => [
      (mirror.spec.environment.notes.find((note) => note.startsWith('scale:')) ?? 'scale:?').slice(
        'scale:'.length,
      ),
      (mirror.result.metrics.find((metric) => metric.name === PRIMARY) ?? { value: Number.NaN })
        .value,
    ]),
  );
  const ideaSmokeValue = scaleValues.get('smoke') ?? Number.NaN;
  expect(ideaSmokeValue).toBeGreaterThan(baselineSmokeValue);
  expect(ideaQuickValue).toBeGreaterThan(baselineSmokeValue);
  // Equal-weight weighting is the loser on this table by construction: the
  // baseline is below the balanced rule's own margin, and both numbers came out
  // of a child process reading the CSV.
  expect(baselineSmokeValue).toBeLessThan(0.8);

  // 8. analyze → handoff. `--harness fake` keeps the deterministic ladder in
  //    charge of the verdict and takes the model out of the test.
  const analyze = await runCli(dir, ['idea', 'analyze', IDEA, '--harness', 'fake', '--json']);
  expect(analyze.code, analyze.stdout + analyze.stderr).toBe(0);
  const analysis = JSON.parse(analyze.stdout) as {
    analysis: { verdict: string; ladderVerdict?: string; baselineComparison?: unknown[] };
  };
  expect(analysis.analysis.verdict, analyze.stdout).toBe('supported');

  const handoff = await runCli(dir, ['idea', 'handoff', IDEA, '--json']);
  expect(handoff.code, handoff.stdout + handoff.stderr).toBe(0);
  const handoffPayload = JSON.parse(handoff.stdout) as {
    level: string;
    handoffReady: boolean;
    blockers: string[];
  };
  expect(handoffPayload.blockers, JSON.stringify(handoffPayload)).toEqual([]);
  expect(handoffPayload.level).toBe('HANDOFF_READY');

  // 9. fairness → plan → approve.
  const fairness = await runCli(dir, ['full', 'fairness', '--idea', IDEA, '--json']);
  expect(fairness.code, fairness.stdout + fairness.stderr).toBe(0);
  const confirm = await runCli(dir, ['full', 'fairness', '--idea', IDEA, '--confirm', '--json']);
  expect(confirm.code, confirm.stdout + confirm.stderr).toBe(0);
  const plan = await runCli(dir, ['full', 'plan', '--idea', IDEA, '--json']);
  expect(plan.code, plan.stdout + plan.stderr).toBe(0);
  const planPayload = JSON.parse(plan.stdout) as {
    plan: { readiness: { ready: boolean; blockers: string[] }; inputHash: string };
  };
  expect(planPayload.plan.readiness.blockers, JSON.stringify(planPayload.plan.readiness)).toEqual(
    [],
  );
  expect(planPayload.plan.readiness.ready).toBe(true);
  const approve = await runCli(dir, ['full', 'approve', '--idea', IDEA, '--confirm', '--json']);
  expect(approve.code, approve.stdout + approve.stderr).toBe(0);

  return {
    datasetHash,
    baselineSmokeValue,
    ideaSmokeValue,
    ideaQuickValue,
    ideaSnapshot,
  };
}

async function reconfirmAndApprove(dir: string): Promise<string> {
  const fairness = await runCli(dir, ['full', 'fairness', '--idea', IDEA, '--json']);
  expect(fairness.code, fairness.stdout + fairness.stderr).toBe(0);
  const confirm = await runCli(dir, ['full', 'fairness', '--idea', IDEA, '--confirm', '--json']);
  expect(confirm.code, confirm.stdout + confirm.stderr).toBe(0);
  const plan = await runCli(dir, ['full', 'plan', '--idea', IDEA, '--json']);
  expect(plan.code, plan.stdout + plan.stderr).toBe(0);
  const approve = await runCli(dir, ['full', 'approve', '--idea', IDEA, '--confirm', '--json']);
  expect(approve.code, approve.stdout + approve.stderr).toBe(0);
  return (JSON.parse(approve.stdout) as { planInputHash: string }).planInputHash;
}

async function waitFor(
  predicate: () => Promise<boolean>,
  { timeoutMs, intervalMs = 500, what }: { timeoutMs: number; intervalMs?: number; what: string },
): Promise<void> {
  const started = Date.now();
  for (;;) {
    if (await predicate()) return;
    if (Date.now() - started > timeoutMs) throw new Error(`timed out waiting for ${what}`);
    await new Promise((resolve) => setTimeout(resolve, intervalMs));
  }
}

