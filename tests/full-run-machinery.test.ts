/**
 * One program, two objectives. `objective` is the whole difference between the
 * published baseline and the idea, which is exactly the mechanism the card
 * claims: the baseline weights every training SAMPLE equally, the idea weights
 * every CLASS equally. Both fit a threshold by scanning held-out-free cut
 * points on the train split and report the protocol metrics on the test split.
 *
 * Scale honesty (#21): the entry reports the scale IT ran, and the smoke slice
 * really is a subsample. The `full` branch may hold for a bounded number of
 * seconds via HOLD_ENV so a long-running work item can be interrupted by the
 * pause test; that hold changes wall-clock only, never the numbers.
 */
function entryProgram(header: string, objectiveBody: string, defaultScale: string): string {
  return `"""${header}

Part of the ideaseek full-run machinery test. Stdlib only: the box running the
suite is not promised numpy, and matplotlib is broken on it.
"""
import csv
import json
import os
import sys
import time

DATA = os.path.join("data", "samples.csv")


def load(path):
    rows = []
    with open(path, newline="") as fh:
        for rec in csv.DictReader(fh):
            rows.append((float(rec["x"]), int(rec["label"]), rec["split"]))
    return rows


def slice_for(rows, scale):
    # smoke = every other row of the sorted table (both classes, both splits);
    # quick and full consume the whole table, which is all this dataset holds.
    return rows[1::2] if scale == "smoke" else rows


def cuts(train):
    xs = sorted(r[0] for r in train)
    out = [xs[0] - 1.0]
    for a, b in zip(xs, xs[1:]):
        if b > a:
            out.append((a + b) / 2.0)
    return out


def scores(rows, t):
    tp = fp = tn = fn = 0
    for x, y, _split in rows:
        pred = 1 if x > t else 0
        if y == 1 and pred == 1:
            tp += 1
        elif y == 1:
            fn += 1
        elif pred == 1:
            fp += 1
        else:
            tn += 1
    rec_minority = tp / (tp + fn) if tp + fn else 0.0
    rec_majority = tn / (tn + fp) if tn + fp else 0.0
    total = tp + fp + tn + fn
    return {
        "balanced_accuracy": (rec_minority + rec_majority) / 2.0,
        "minority_recall": rec_minority,
        "accuracy": (tp + tn) / total if total else 0.0,
    }


def objective(m):
${objectiveBody}


def asked_scale(argv):
    """The scale this process actually ran at — never the one it was labelled.

    Positional form (\`reproduce.py smoke\`) is what \`baseline reproduce\` uses;
    flag form (\`--scale quick\`) is what \`idea experiment\` uses. With neither,
    the file's own entry default applies, and the full-scale branch is the one
    that may hold for the bounded test pause.
    """
    for i, token in enumerate(argv):
        if token == "--scale" and i + 1 < len(argv):
            return argv[i + 1]
    if argv and argv[0] in ("smoke", "quick", "full"):
        return argv[0]
    return ${JSON.stringify(defaultScale)}


def main(argv):
    cmd = argv[0] if argv else ""
    if cmd == "check-data":
        rows = load(DATA)
        classes = {r[1] for r in rows}
        splits = {r[2] for r in rows}
        if len(rows) < 50 or len(classes) != 2 or len(splits) != 2:
            sys.stderr.write("data interface does not hold: %d rows\\n" % len(rows))
            return 1
        return 0
    if cmd == "check-metrics":
        rows = [r for r in load(DATA) if r[2] == "test"]
        m = scores(rows, 1.0)
        for name in ("balanced_accuracy", "minority_recall"):
            if not isinstance(m[name], float):
                sys.stderr.write("metric %s is not a float\\n" % name)
                return 1
        return 0
    scale = asked_scale(argv)
    if scale == "full":
        hold = float(os.environ.get(${JSON.stringify(HOLD_ENV)}, "0") or "0")
        if hold > 0:
            time.sleep(hold)
    rows = slice_for(load(DATA), scale)
    train = [r for r in rows if r[2] == "train"]
    test = [r for r in rows if r[2] == "test"]
    best_t = None
    best = None
    for t in cuts(train):
        value = objective(scores(train, t))
        if best is None or value > best + 1e-12:
            best = value
            best_t = t
    out = scores(test, best_t)
    print(json.dumps({
        "metrics": {
            "balanced_accuracy": out["balanced_accuracy"],
            "minority_recall": out["minority_recall"],
        },
        "scale": scale,
        "fit_threshold": best_t,
    }))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
`;
}

