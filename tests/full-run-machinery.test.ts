async function latestRunId(dir: string): Promise<string> {
  const rt = await openRuntime(dir, { recover: false });
  try {
    const run = await rt.db.getLatestRun(rt.project.id);
    if (!run) throw new Error('no run recorded yet');
    return run.runId;
  } finally {
    await rt.close();
  }
}

async function taskState(
  dir: string,
  runId: string,
  type: string,
): Promise<{
  status: string;
  attemptsMade: number;
  error: { code: string; message: string } | null;
}> {
  const rt = await openRuntime(dir, { recover: false });
  try {
    const tasks = await rt.db.listTasks(runId);
    const task = tasks.filter((row) => row.type === type).pop();
    if (!task) throw new Error(`no ${type} task in ${runId}`);
    return {
      status: task.status,
      attemptsMade: task.attempt,
      error: task.error ? { code: task.error.code, message: task.error.message } : null,
    };
  } finally {
    await rt.close();
  }
}

